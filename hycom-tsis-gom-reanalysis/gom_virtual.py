# ------------------------------------------------------------------ constants

BUCKET, REGION = "hycom-tsis-gom-reanalysis", "us-west-2"
# HTTPS rather than s3:// references, as in GOFS 3.1: readers need no AWS client or region setup,
# and a browser can read the bytes if the bucket is ever given a CORS policy.
URL_PREFIX = f"https://{BUCKET}.s3.{REGION}.amazonaws.com/data/"
GROUP = "hourly"                       # may be renamed later (#15); keep it a parameter
START, END = pd.Timestamp("2001-01-16 00:00"), pd.Timestamp("2024-04-28 23:00")

VARS_2D = ("ssh", "mixed_layer_thickness", "u_barotropic_velocity", "v_barotropic_velocity",
           "wnd_ewd", "wnd_nwd")
VARS_3Z = ("u", "v", "w_velocity", "water_temp", "salinity")
VARS = {"2d": VARS_2D, "3z": VARS_3Z}

NY, NX, NZ = 1537, 2101, 40
TY, TX, SRC_DZ = 385, 526, 10          # 3z source chunk: 10 depths of a 385 x 526 tile
NTY, NTX = -(-NY // TY), -(-NX // TX)  # 4 x 4 tiles; the edge tiles are stored padded to full size
LEVEL_BYTES = TY * TX * 4              # one depth of one tile, contiguous: 810,040 bytes
CHUNK_BYTES = {"2d": NY * NX * 4, "3z": SRC_DZ * LEVEL_BYTES}
# Fill values (R21, decided by Eli 2026-11-19). In every layout A file sampled, every
# variable's `_FillValue` attribute is float32(1.267651e30) (bits 1904214019), but land is written
# as 2**100 = 1.2676506e30 (bits 1904214016), 3 ulps away. CF readers mask by exact equality, so
# xarray on a source file leaves all 945,478 land points at 1.27e30. The store declares the value
# actually on land, so land and gap hours both read as missing. Metadata only; no data change.
SOURCE_FILL_ATTR = np.float32(1.267651e30)
FILL = np.float32(2.0 ** 100)


def _fill_attr():
    from xarray.backends.zarr import FillValueCoder
    return FillValueCoder.encode(FILL, np.dtype("float32"))


_FILL_ATTR = _fill_attr()

# Far below any good file and far above the empty 3z files (239 B / 49 KB). Truncation is caught
# by the chunk-extent check in the scan, not by this. One good 2d file is 102 kB larger than the
# rest (2004_153_19), so no upper bound.
MIN_SIZE = {"2d": 77_000_000, "3z": 2_590_000_000}

# Regenerated by HYCOM on 2026-11-10; left out until HYCOM says which version is good (plan,
# "For the HYCOM team", item 2).
HELD_BACK = frozenset(f"2002/010_archv.2002_{dh}_3z.nc"
                      for dh in ("046_12", "046_16", "051_06", "051_07", "051_09"))

KEY_RE = re.compile(r"^(?P<year>\d{4})/(?P<exp>010|023|026)_archv\.(?P=year)_(?P<day>\d{3})_"
                    r"(?P<hour>\d{2})_(?P<kind>2d|3z)\.nc$")
EPOCH = pd.Timestamp("1900-12-31")     # MT: days since 1900-12-31 00:00:00, as in the files
HDF5_INTERNAL = {"_Netcdf4Coordinates", "_Netcdf4Dimid", "CLASS", "NAME", "DIMENSION_LIST",
                 "REFERENCE_LIST", "_NCProperties"}


def source_store():
    from obstore.store import S3Store
    return S3Store(BUCKET, region=REGION, skip_signature=True)


def time_of(year, day, hour) -> pd.Timestamp:
    """Valid time from the filename. Not from `MT`, which is float32-rounded in 3z (audit F8)."""
    return pd.Timestamp(f"{int(year)}-01-01") + pd.Timedelta(days=int(day) - 1, hours=int(hour))


def hourly_axis(start=START, end=END) -> pd.DatetimeIndex:
    """Regular hourly; hours with no file stay on the axis and read as missing."""
    return pd.date_range(start, end, freq="h")


# ------------------------------------------------------------------ discovery

def list_keys(store, years) -> pd.DataFrame:
    """Every object under data/<year>/, keys relative to data/."""
    import obstore
    rows = []
    for y in years:
        for batch in obstore.list(store, prefix=f"data/{y}/", chunk_size=1000):
            rows += [(o["path"].removeprefix("data/"), o["size"], o["last_modified"]) for o in batch]
    return pd.DataFrame(rows, columns=["key", "size", "modified"])


def select_files(listing: pd.DataFrame, start=START, end=END) -> tuple[pd.DataFrame, pd.DataFrame]:
    """(files, skipped). `files` has one row per layout A file; `skipped` says why each other key
    was left out. Daily means and config files are not hourly and are not listed as skipped."""
    keep, skip = [], []
    for key, size, modified in listing.itertuples(index=False):
        if "/" not in key or "_archv." not in key:
            continue
        m = KEY_RE.match(key)
        if not m:
            reason = ("layout B experiment (027/028)" if re.search(r"/02[78]_archv\.", key)
                      else "not an hourly file name (_CORRUPTED, _COPY, stray)")
            skip.append((key, size, reason))
            continue
        t = time_of(m["year"], m["day"], m["hour"])
        if not start <= t <= end:
            skip.append((key, size, "outside the time range"))
        elif key in HELD_BACK:
            skip.append((key, size, "held back: regenerated 2026-11-10, waiting for HYCOM"))
        elif size < MIN_SIZE[m["kind"]]:
            skip.append((key, size, "too small: empty file"))
        else:
            keep.append(dict(key=key, size=int(size), modified=modified, time=t,
                             kind=m["kind"], experiment=int(m["exp"])))
    files = pd.DataFrame(keep, columns=["key", "size", "modified", "time", "kind", "experiment"])
    dup = files.duplicated(["time", "kind"], keep=False)
    assert not dup.any(), f"two files for one hour: {files[dup].key.tolist()[:6]}"
    return files.sort_values(["time", "kind"]).reset_index(drop=True), \
        pd.DataFrame(skip, columns=["key", "size", "reason"])


# ------------------------------------------------------------------ header scan

def _clean_attrs(attrs) -> dict:
    """HDF5 attributes as JSON-able Python values, without HDF5/netCDF-4 bookkeeping."""
    out = {}
    for k, v in attrs.items():
        if k in HDF5_INTERNAL:
            continue
        if isinstance(v, bytes):
            v = v.decode()
        elif isinstance(v, np.ndarray):
            v = v.item() if v.size == 1 else v.tolist()
        elif isinstance(v, np.generic):
            v = v.item()
        out[k] = v
    return out


def _check_extent(key, size, kind, offsets):
    end = int(offsets.max()) + CHUNK_BYTES[kind]
    if end > size or (offsets == 0).any():
        raise ValueError(f"{key}: chunk data end at {end:,} beyond the file's {size:,} bytes (truncated?)")


def scan_h5py(store, key: str, kind: str, size: int) -> dict:
    """Parser (b): each variable's source-chunk byte offsets, read from the file's own HDF5 chunk
    index, plus what must be the same in every file. Raises if the file is not layout A."""
    import h5py
    from obspec_utils.readers import BlockStoreReader
    shape, chunks = ((1, NZ, NY, NX), (1, SRC_DZ, TY, TX)) if kind == "3z" else ((1, NY, NX), (1, NY, NX))
    grid = tuple(-(-s // c) for s, c in zip(shape, chunks))
    out = {"offsets": {}, "attrs": {}}
    with h5py.File(BlockStoreReader(store, "data/" + key)) as f:
        out["global_attrs"] = _clean_attrs(f.attrs)
        # Coordinate fingerprints. The header block is already read, so this costs nothing.
        # The 3z Longitude of 023/026 files differs from the 2d one by up to 3e-5 deg; this
        # shows where such changes happen without failing the file.
        import hashlib
        out["coords_md5"] = {n: hashlib.md5(f[n][:].tobytes()).hexdigest()[:8]
                             for n in ("Latitude", "Longitude", "Depth") if n in f}
        # The file's own MT, for the gap-fill gate's time check (#22). 3z MT is float32-rounded
        # (audit F8), so it is only compared with the filename to the hour, never used as the axis.
        out["MT"] = float(np.ravel(f["MT"][:])[0]) if "MT" in f and f["MT"].size else None
        for name in VARS[kind]:
            d = f[name]
            if (d.shape, d.chunks, d.dtype.str, d.compression, d.shuffle) != (shape, chunks, "<f4", None, False):
                raise ValueError(f"{key}:{name} is not layout A: {d.shape} {d.chunks} {d.dtype.str} {d.compression}")
            fv = d.attrs.get("_FillValue")
            if fv is None or np.float32(np.ravel(fv)[0]).view("u4") != SOURCE_FILL_ATTR.view("u4"):
                raise ValueError(f"{key}:{name} _FillValue {fv!r} is not the layout A value")
            offs = np.zeros(grid, "uint64")
            for i in range(d.id.get_num_chunks()):
                c = d.id.get_chunk_info(i)
                if c.size != CHUNK_BYTES[kind]:
                    raise ValueError(f"{key}:{name} chunk {c.chunk_offset} is {c.size} bytes")
                offs[tuple(o // n for o, n in zip(c.chunk_offset, chunks))] = c.byte_offset
            _check_extent(key, size, kind, offs)
            out["offsets"][name] = offs
            out["attrs"][name] = _clean_attrs(d.attrs)
    out["cell_methods"] = _file_cell_methods(key, out["attrs"])
    return out


def scan_hdfparser(registry, key: str, kind: str, size: int) -> dict:
    """Parser (a): the same offsets from VirtualiZarr's HDFParser."""
    from virtualizarr import open_virtual_dataset
    from virtualizarr.parsers import HDFParser
    vds = open_virtual_dataset(f"s3://{BUCKET}/data/{key}", registry=registry, parser=HDFParser(),
                               loadable_variables=[])
    out = {"offsets": {}, "attrs": {}, "global_attrs": dict(vds.attrs)}
    want = (1, SRC_DZ, TY, TX) if kind == "3z" else (1, NY, NX)
    for name in VARS[kind]:
        ma = vds[name].data
        chunk = tuple(ma.metadata.chunk_grid.chunk_shape)
        if chunk != want or ma.dtype != np.float32:
            raise ValueError(f"{key}:{name} is not layout A: chunks {chunk}, {ma.dtype}")
        if not (ma.manifest._lengths == CHUNK_BYTES[kind]).all():
            raise ValueError(f"{key}:{name} has a chunk of unexpected length")
        offs = ma.manifest._offsets.astype("uint64")
        _check_extent(key, size, kind, offs)
        out["offsets"][name] = offs
        out["attrs"][name] = {k: v for k, v in vds[name].attrs.items() if k != "_FillValue"}
    out["cell_methods"] = _file_cell_methods(key, out["attrs"])
    return out


def _file_cell_methods(key: str, attrs: dict) -> str | None:
    """The file's `cell_methods` (R22). HYCOM writes it on every variable of a file it rebuilt with
    ncra, so all variables must agree; None on model output."""
    values = {a.get("cell_methods") for a in attrs.values()}
    if len(values) != 1:
        raise ValueError(f"{key}: variables disagree on cell_methods: {values}")
    return values.pop()


def fingerprint(scan: dict) -> str:
    """What should be identical across layout A files: attributes apart from the per-hour
    `valid_range`. A different fingerprint is reported, not fatal: HYCOM's interpolated stand-ins
    carry `cell_methods` and a different `history` (audit F5), and those are worth listing."""
    import hashlib, json
    doc = {"g": {k: v for k, v in scan["global_attrs"].items() if k != "_NCProperties"},
           "v": {n: {k: v for k, v in a.items() if k != "valid_range"} for n, a in scan["attrs"].items()}}
    return hashlib.md5(json.dumps(doc, sort_keys=True, default=str).encode()).hexdigest()[:10]


_WORKER: dict = {}


def _scan_one(args):
    """One file, in a worker process. Retries, because S3 drops a connection now and then and
    that is not corruption; a ValueError is a layout problem and is not retried."""
    key, kind, size, method, attempts = args
    if method not in _WORKER:
        store = source_store()
        if method == "hdfparser":
            from obspec_utils.registry import ObjectStoreRegistry
            registry = ObjectStoreRegistry({f"s3://{BUCKET}": store})
            _WORKER[method] = lambda k, kd, sz: scan_hdfparser(registry, k, kd, sz)
        else:
            _WORKER[method] = lambda k, kd, sz: scan_h5py(store, k, kd, sz)
    fn, t0, err = _WORKER[method], time.perf_counter(), None
    for i in range(attempts):
        try:
            s = fn(key, kind, size)
            return key, s, dict(key=key, seconds=time.perf_counter() - t0, error=None,
                                fingerprint=fingerprint(s), attempts=i + 1)
        except Exception as e:  # noqa: BLE001 - recorded per file, never silently dropped
            err = f"{type(e).__name__}: {e}"
            if isinstance(e, ValueError):
                break
    return key, None, dict(key=key, seconds=time.perf_counter() - t0, error=err, fingerprint=None,
                           attempts=i + 1)


def scan_files(files: pd.DataFrame, method: str = "h5py", workers: int = 16,
               attempts: int = 3) -> tuple[dict, pd.DataFrame]:
    """Scan every file; ({key: scan}, report). A file that fails is reported with its error and
    left out, so its hour reads as missing.

    Processes, not threads: h5py serializes every call on one global lock, and the parser's
    reads happen inside those calls, so threads give no parallelism at all (measured
    2026-11-19: 8 files took as long on 8 threads as 4 files serially). HDFParser uses h5py too.
    Workers mostly wait on S3, so more of them than cores is fine."""
    from concurrent.futures import ProcessPoolExecutor
    import multiprocessing as mp
    jobs = [(r.key, r.kind, r.size, method, attempts) for r in files.itertuples(index=False)]
    # forkserver: fork after obstore/tokio threads exist can deadlock a child
    with ProcessPoolExecutor(workers, mp_context=mp.get_context("forkserver")) as ex:
        results = list(ex.map(_scan_one, jobs, chunksize=max(1, len(jobs) // (workers * 8))))
    scans = {k: s for k, s, _ in results if s is not None}
    return scans, pd.DataFrame([r for _, _, r in results])


# ------------------------------------------------------------------ references

def split_depths(offsets: np.ndarray, d: int) -> np.ndarray:
    """3z source chunks (.., 4 depth groups, 4, 4) of 10 depths -> (.., 40/d, 4, 4) chunks of d
    depths. Uncompressed, so depths j*d..j*d+d-1 of a tile start j*d levels into its chunk."""
    assert SRC_DZ % d == 0, d
    k = SRC_DZ // d
    step = np.arange(k, dtype="uint64") * np.uint64(d * LEVEL_BYTES)
    out = offsets[:, :, None, :, :] + step[None, None, :, None, None]
    return out.reshape(offsets.shape[0], offsets.shape[1] * k, *offsets.shape[2:])


# ------------------------------------------------------------------ metadata (repairs R1-R20)

def science_attrs(name: str, source: dict) -> dict:
    a = {k: v for k, v in source.items() if k not in ("_FillValue", "valid_range", "coordinates", "cell_methods")}
    # R22: cell_methods is per hour, so it lives in the flag variable, linked here.
    a["ancillary_variables"] = "cell_methods_3z" if name in VARS_3Z else "cell_methods_2d"
    # R7 valid_range dropped (per-hour min/max); R20 `coordinates` is written by xarray from the
    # dataset's coordinates. long_name kept verbatim, [01.0H] and spacing included (R8, as GOFS).
    if name == "ssh":
        a["standard_name"] = "sea_surface_height_above_geoid"          # R9: the source's is an alias
    if name == "salinity":                                              # R10, as GOFS
        a.update(units="1e-3", source_units=source["units"], long_name="Sea Water Salinity")
    if name == "water_temp":
        a["units_metadata"] = "temperature: on_scale"                   # R11 (CF-1.11 s3.1.2)
    return a


def global_attrs(source: dict) -> dict:
    a = {k: v for k, v in source.items() if k != "_NCProperties"}      # R17
    a.update(                                                           # R15, R16, R18
        Conventions="CF-1.11", source_Conventions=source["Conventions"],
        title="HYCOM-TSIS GOMb0.01 Gulf of Mexico reanalysis, hourly", source_title=source["title"],
        references="https://www.hycom.org/data/gomb0pt01/gom-reanalysis",
        source_data=f"s3://{BUCKET} ({REGION}), NetCDF-4/HDF5, one file per hour and kind (2d, 3z); "
                    "experiments 010, 023 and 026 (chunk layout A)",
        comment="Virtual Icechunk store: Zarr metadata and byte-range references only. The arrays stay "
                "in the source NetCDF files and are read from there. Hours with no source file are on "
                "the time axis and read as missing; `experiment` is 0 where neither file exists.",
    )
    return a


def read_grid(store, key2d: str, key3z: str) -> dict:
    """Latitude and Longitude from a 2d file, Depth from a 3z file (values and attributes).

    From the 2d file because its Longitude is the same in every file sampled, equal to
    float32(-98 + 0.01 i) and to topo/'s. The 3z Longitude of 023/026 files differs by up
    to 3e-5 deg. `valid_range`, which some 3z files put on the coordinates, is dropped (R7)."""
    import h5py
    from obspec_utils.readers import BlockStoreReader
    out = {}
    for key, names in ((key3z, ("Depth",)), (key2d, ("Latitude", "Longitude"))):
        with h5py.File(BlockStoreReader(store, "data/" + key)) as f:
            for n in names:
                a = _clean_attrs(f[n].attrs)
                a.pop("valid_range", None)
                out[n] = (f[n][:], a)
    return {n: out[n] for n in ("Depth", "Latitude", "Longitude")}


def read_topo(store, grid: dict) -> dict:
    """bathy and mask from topo/ (NetCDF-3), checked against the data grid."""
    import obstore
    out = {}
    for name, f in (("bathy", "depth"), ("mask", "mask")):
        buf = bytes(obstore.get(store, f"topo/regional.{f}.nc").bytes())
        with xr.open_dataset(io.BytesIO(buf), engine="scipy", decode_times=False) as ds:
            assert np.array_equal(ds["lat"].values[:, 0], grid["Latitude"][0]), name
            assert np.array_equal(ds["lon"].values[0, :], grid["Longitude"][0]), name
            out[name] = (ds[name].values.copy(), dict(ds[name].attrs))
    return out


# R22 (decided by Eli, 2026-11-19): each hour's `cell_methods`, from the files' own attributes.
CELL_METHODS_FLAGS = {None: 0, "MT: mean": 1}       # 2 = no source file (or the file was skipped)
NO_FILE_FLAG = 2


def cell_methods_flags(times: pd.DatetimeIndex, files: pd.DataFrame, scans: dict) -> dict:
    """{kind: int8 array along times}. A value the scan finds that is not in CELL_METHODS_FLAGS
    stops the build, so a new kind of HYCOM stand-in is reviewed before it is labelled."""
    out = {}
    for kind in VARS:
        flags = np.full(len(times), NO_FILE_FLAG, "i1")
        rows = files[(files.kind == kind) & files.key.isin(list(scans)) & files.time.isin(times)]
        for t, key in zip(rows.time, rows.key):
            cm = scans[key]["cell_methods"]
            if cm not in CELL_METHODS_FLAGS:
                raise ValueError(f"{key}: cell_methods {cm!r} has no flag yet; review it before building")
            flags[times.get_loc(t)] = CELL_METHODS_FLAGS[cm]
        out[kind] = flags
    return out


def loaded_variables(times: pd.DatetimeIndex, files: pd.DataFrame, grid: dict, topo: dict,
                     scans: dict) -> xr.Dataset:
    """Everything written as real data: the coordinates, Date, experiment, bathy and mask."""
    nt = len(times)
    one = {"chunks": (nt,), "_FillValue": None}       # one chunk for the whole axis
    # Source convention verbatim (decided): float64 days since 1900-12-31 00:00:00, the values as
    # the 2d files hold them. Written as plain numbers with the source's units string, because
    # xarray's own datetime encoding would shorten the units to "days since 1900-12-31".
    mt = ((times - EPOCH) / pd.Timedelta(days=1)).to_numpy("f8")
    MT = xr.Variable("MT", mt, {
        "long_name": "time", "units": "days since 1900-12-31 00:00:00", "calendar": "standard",
        "axis": "T", "standard_name": "time",                           # R2
        "units_metadata": "leap_seconds: unknown"}, encoding=dict(one))  # R19 (CF-1.11 s4.4, as GOFS)
    date = (times.year * 10000 + times.month * 100 + times.day).to_numpy("f8") + times.hour.to_numpy() / 24
    Date = xr.Variable("MT", date, {                                    # R3, R4 (as GOFS did for tau)
        "long_name": "date (YYYYMMDD.fraction of day)", "source_units": "day as %Y%m%d.%f",
        "C_format": "%13.4f", "FORTRAN_format": "(f13.4)"}, encoding=dict(one))
    used = files[files.key.isin(list(scans))]        # a skipped file does not count as present
    present = used.drop_duplicates("time").set_index("time")["experiment"].reindex(times)
    experiment = xr.Variable("MT", present.fillna(0).to_numpy("i2"), {     # R12
        "long_name": "experiment number in the source file names (0: no file for this hour)",
        "flag_values": np.array([0, 10, 23, 26], "i2"),
        "flag_meanings": "no_source_file expt_010 expt_023 expt_026"}, encoding=dict(one))
    coords = {n: xr.Variable(n, v.astype("f4"), dict(a), encoding={"_FillValue": None})   # R5
              for n, (v, a) in grid.items()}
    coords["Latitude"].attrs.setdefault("long_name", "Latitude")        # R6
    coords["Longitude"].attrs.setdefault("long_name", "Longitude")
    bathy_v, bathy_a = topo["bathy"]
    mask_v, mask_a = topo["mask"]
    bathy = xr.Variable(("Latitude", "Longitude"), bathy_v.astype("f4"), {    # R13
        **bathy_a, "units": "m", "positive": "down", "standard_name": "sea_floor_depth_below_geoid",
        "comment": "0 on land. From topo/regional.depth.nc."}, encoding={"_FillValue": None})
    mask = xr.Variable(("Latitude", "Longitude"), mask_v.astype("i1"), {      # R14
        **mask_a, "standard_name": "sea_binary_mask", "flag_values": np.array([0, 1], "i1"),
        "flag_meanings": "land sea", "comment": "From topo/regional.mask.nc."}, encoding={"_FillValue": None})
    flags = cell_methods_flags(times, files, scans)
    cm = {f"cell_methods_{kind}": xr.Variable("MT", flags[kind], {             # R22
        "long_name": f"cell_methods of this hour's {kind} source file",
        "flag_values": np.array([0, 1, 2], "i1"),
        "flag_meanings": "none MT_mean no_source_file",
        "comment": f"From the `cell_methods` attribute of each {kind} file. HYCOM rebuilt some hours as the "
                   "mean of the neighbouring hours with ncra and marked them cell_methods = \"MT: mean\"; "
                   "those hours are not model output. 0: no cell_methods (model output); 2: no file, "
                   "or the file was skipped."}, encoding=dict(one)) for kind in VARS}
    return xr.Dataset({"bathy": bathy, "mask": mask},
                      coords={"MT": MT, **coords, "Date": Date, "experiment": experiment, **cm})


def virtual_variables(times: pd.DatetimeIndex, files: pd.DataFrame, scans: dict, d: int,
                      src_attrs: dict | None) -> xr.Dataset:
    """The 11 science variables over `times`, referencing whichever scanned files fall in it.
    Hours with no scan get an empty path: no reference, so the chunk reads as the fill value."""
    from virtualizarr.manifests import ChunkManifest, ManifestArray
    from virtualizarr.manifests.utils import create_v3_array_metadata
    nt, out = len(times), {}
    inside = files[(files.time >= times[0]) & (files.time <= times[-1]) & files.key.isin(list(scans))]
    for kind, names in VARS.items():
        rows = inside[inside.kind == kind]
        where = times.get_indexer(rows.time)
        assert (where >= 0).all()
        if kind == "3z":
            dims, shape, chunk = ("MT", "Depth", "Latitude", "Longitude"), (nt, NZ, NY, NX), (1, d, TY, TX)
            grid, length = (nt, NZ // d, NTY, NTX), d * LEVEL_BYTES
        else:
            dims, shape, chunk = ("MT", "Latitude", "Longitude"), (nt, NY, NX), (1, NY, NX)
            grid, length = (nt, 1, 1), CHUNK_BYTES["2d"]
        for name in names:
            paths = np.full(grid, "", dtype=np.dtypes.StringDType())
            offsets = np.zeros(grid, "uint64")
            lengths = np.zeros(grid, "uint64")
            for i, key in zip(where, rows.key):
                o = scans[key]["offsets"][name]
                offsets[i] = split_depths(o, d)[0] if kind == "3z" else o[0]
                paths[i] = URL_PREFIX + key
                lengths[i] = length
            metadata = create_v3_array_metadata(
                shape=shape, chunk_shape=chunk, data_type=np.dtype("float32"),
                codecs=[{"name": "bytes", "configuration": {"endian": "little"}}],   # uncompressed
                fill_value=float(FILL), dimension_names=dims)
            manifest = ChunkManifest.from_arrays(paths=paths, offsets=offsets, lengths=lengths)
            # VirtualiZarr writes ManifestArray attributes as given, without xarray's encoding step,
            # and xarray (2026.9) reads a float _FillValue in Zarr v3 only in its own base64 form
            # (what HDFParser emits too). So encode it here as xarray would; a plain float fails to open.
            # src_attrs=None (gap fills, #22): no attributes, so the region write's attribute update
            # is a no-op and the stored ones stay exactly as the build wrote them. Taking them from a
            # fill file instead could carry an ncra stand-in's attributes onto the whole array.
            attrs = ({} if src_attrs is None else
                     {**science_attrs(name, src_attrs[name]), "_FillValue": _FILL_ATTR})
            out[name] = xr.Variable(dims, ManifestArray(metadata=metadata, chunkmanifest=manifest), attrs=attrs)
    return xr.Dataset(out)


